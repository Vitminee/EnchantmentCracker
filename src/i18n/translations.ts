let currentLang: keyof typeof translations = 'en';

export function setLanguage(lang: keyof typeof translations) {
  if (translations[lang]) currentLang = lang;
}

export function getLanguage(): string {
  return currentLang;
}

export function translate(key: string, ...args: (string | number)[]): string {
  const langDict = (translations as any)[currentLang] || translations.en;
  let text: string = langDict[key] ?? (translations.en as any)[key] ?? key;
  if (args.length > 0) {
    for (const arg of args) {
      text = text.replace(/%[0-9]*\.?[0-9]*[sfdX]/, String(arg));
    }
  }
  return text;
}
